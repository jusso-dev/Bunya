// New-AzWebApp, New-AzFunctionApp and New-AzContainerRegistry cannot turn
// public network access off.
const NO_PRIVATE_CREATE: ReadonlySet<ServiceType> = new Set(["appService", "functionApp", "containerRegistry"]);

function header(document: GraphDocument, includeSqlAdmin: boolean): string[] {
  const lines = [
    `<#`,
    `.SYNOPSIS`,
    `    Deploys the ${document.metadata.name} architecture to Azure using the Az module.`,
    `.DESCRIPTION`,
    `    Generated by Bunya. Re-runnable. Honours -WhatIf and -Confirm.`,
    `.PARAMETER ResourceGroupName`,
    `    Resource Group to deploy into. Defaults to the value embedded in the document.`,
    `.PARAMETER Location`,
    `    Azure region. Defaults to ${document.metadata.region}.`,
  ];
  if (includeSqlAdmin) {
    lines.push(
      `.PARAMETER SqlAdminPassword`,
      `    Secure string for the SQL Server admin password.`,
    );
  }
  lines.push(
    `.NOTES`,
    `    Requires Az.Accounts, Az.Resources, Az.Websites, Az.Storage, Az.KeyVault,`,
    `    Az.Sql, Az.CosmosDB, Az.Network, Az.OperationalInsights, Az.ApplicationInsights,`,
    `    Az.ApiManagement, Az.ContainerRegistry, Az.ManagedServiceIdentity.`,
    `#>`,
  );
  return lines;
}

function emitNode(node: GraphNode, ctx: GeneratorContext): string[] {
  const name = ctx.name(node.id);
  const region = ctx.document.metadata.region;
  switch (node.type) {
    case "resourceGroup":
      return [
        `# Resource Group ${name}`,
        `$rgParams = @{`,
        `    Name     = '${name}'`,
        `    Location = '${region}'`,
        `    Tag      = @{ environment = '${ctx.document.metadata.environment}'; managed_by = 'bunya' }`,
        `}`,
        `New-AzResourceGroup @rgParams -Force | Out-Null`,
      ];
    case "virtualNetwork":
      return [
        `# Virtual Network ${name}`,
        `$vnetParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `    AddressPrefix     = @(${[String(node.properties.addressSpace), ...((node.properties.additionalAddressSpaces as string[]))].map((space) => `'${space}'`).join(", ")})`,
        `}`,
        `New-AzVirtualNetwork @vnetParams -Force | Out-Null`,
      ];
    case "subnet": {
      const vnetName = ctx.name(subnetVnet(ctx, node).id);
      return [
        `# Subnet ${name}`,
        `$vnet = Get-AzVirtualNetwork -ResourceGroupName $ResourceGroupName -Name '${vnetName}'`,
        `Add-AzVirtualNetworkSubnetConfig -Name '${name}' -VirtualNetwork $vnet -AddressPrefix '${String(node.properties.addressPrefix)}' -PrivateEndpointNetworkPoliciesFlag '${String(node.properties.privateEndpointNetworkPolicies)}' | Out-Null`,
        `$vnet | Set-AzVirtualNetwork | Out-Null`,
      ];
    }
    case "networkSecurityGroup":
      return [
        `# Network Security Group ${name}`,
        `$nsgParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `}`,
        `New-AzNetworkSecurityGroup @nsgParams -Force | Out-Null`,
      ];
    case "privateEndpoint":
      return [
        `# Private Endpoint ${name}`,
        `# Configure with New-AzPrivateEndpoint after upstream resources exist.`,
        `Write-Information 'Skipping ${name} configure step; see Bunya documentation.' -InformationAction Continue`,
      ];
    case "privateDnsZone":
      return [
        `# Private DNS Zone ${name}`,
        `New-AzPrivateDnsZone -ResourceGroupName $ResourceGroupName -Name '${dnsZoneName(node)}' | Out-Null`,
      ];
    case "appServicePlan": {
      const sku = String(node.properties.sku);
      // Non-dedicated plans go through the ARM template instead.
      const plan = powerShellPlanSku(sku)!;
      const lines = [
        `# App Service Plan ${name} (${sku})`,
        `$planParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `    Tier              = '${plan.tier}'`,
        `    NumberofWorkers   = ${Number(node.properties.capacity)}`,
        `    WorkerSize        = '${plan.workerSize}'`,
        `}`,
      ];
      // New-AzAppServicePlan has no -Force parameter.
      return [...lines, `New-AzAppServicePlan @planParams${(node.properties.os as string) === "Linux" ? " -Linux" : ""} | Out-Null`];
    }
    case "appService": {
      const planName = ctx.name(sitePlan(ctx.document, node)!.id);
      return [
        `# App Service ${name}`,
        `$appParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `    AppServicePlan    = '${planName}'`,
        `}`,
        `New-AzWebApp @appParams | Out-Null`,
        `Set-AzWebApp -ResourceGroupName $ResourceGroupName -Name '${name}' -HttpsOnly $${node.properties.httpsOnly !== false} -AssignIdentity $true | Out-Null`,
      ];
    }
    case "functionApp": {
      const planName = ctx.name(sitePlan(ctx.document, node)!.id);
      const stName = ctx.name(targetOfType(ctx, node.id, "data", "storageAccount")!.id);
      return [
        `# Function App ${name}`,
        `$fnParams = @{`,
        `    ResourceGroupName     = $ResourceGroupName`,
        `    Name                  = '${name}'`,
        `    Location              = $Location`,
        `    PlanName              = '${planName}'`,
        `    StorageAccountName    = '${stName}'`,
        `    Runtime               = '${String(node.properties.runtime)}'`,
        `    RuntimeVersion        = '${String(node.properties.runtimeVersion)}'`,
        `    FunctionsVersion      = '4'`,
        `    IdentityType          = 'SystemAssigned'`,
        `}`,
        `New-AzFunctionApp @fnParams | Out-Null`,
      ];
    }
    case "staticWebApp":
      return [
        `# Static Web App ${name}`,
        `$swaParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `    SkuName           = '${String(node.properties.sku)}'`,
        `}`,
        `New-AzStaticWebApp @swaParams | Out-Null`,
      ];
    case "aksCluster":
      return [
        `# AKS ${name}`,
        `Write-Information 'Create AKS ${name} with New-AzAksCluster or deploy the generated Bicep/ARM for full node pool and networking support.' -InformationAction Continue`,
      ];
    case "virtualMachineScaleSet":
      return [
        `# Virtual Machine Scale Set ${name}`,
        `Write-Information 'Create VMSS ${name} with New-AzVmss or deploy the generated Bicep/ARM for SSH key and network profile support.' -InformationAction Continue`,
      ];
    case "storageAccount":
      return [
        `# Storage Account ${name}`,
        `$stgParams = @{`,
        `    ResourceGroupName     = $ResourceGroupName`,
        `    Name                  = '${name}'`,
        `    Location              = $Location`,
        `    SkuName               = '${String(node.properties.sku)}'`,
        `    Kind                  = '${String(node.properties.kind)}'`,
        `    MinimumTlsVersion     = '${tlsVersionToArm(String(node.properties.minTlsVersion))}'`,
        `    AllowBlobPublicAccess = $${node.properties.allowPublicAccess === true}`,
        `    PublicNetworkAccess   = '${storagePublicNetwork(node.properties) ? "Enabled" : "Disabled"}'`,
        `}`,
        `New-AzStorageAccount @stgParams | Out-Null`,
      ];
    case "sqlDatabase": {
      const adminLogin = String(node.properties.adminLogin);
      return [
        `# Azure SQL ${name}`,
        `$srvParams = @{`,
        `    ResourceGroupName             = $ResourceGroupName`,
        `    ServerName                    = '${sqlServerName(ctx, node)}'`,
        `    Location                      = $Location`,
        `    SqlAdministratorCredentials   = (New-Object System.Management.Automation.PSCredential('${adminLogin}', $SqlAdminPassword))`,
        `    MinimalTlsVersion             = '1.2'`,
        `    PublicNetworkAccess           = 'Disabled'`,
        `}`,
        `New-AzSqlServer @srvParams | Out-Null`,
        `$dbParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    ServerName        = '${sqlServerName(ctx, node)}'`,
        `    DatabaseName      = '${name}'`,
        `    RequestedServiceObjectiveName = '${String(node.properties.sku)}'`,
        `}`,
        `New-AzSqlDatabase @dbParams | Out-Null`,
      ];
    }
    case "cosmosDb":
      return [
        `# Cosmos DB ${name}`,
        `$cosParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = @($Location)`,
        `    DefaultConsistencyLevel = '${String(node.properties.consistency)}'`,
        `    EnableFreeTier    = $${node.properties.freeTier === true}`,
        `}`,
        `New-AzCosmosDBAccount @cosParams | Out-Null`,
      ];
    case "keyVault":
      return [
        `# Key Vault ${name}`,
        `$kvParams = @{`,
        `    ResourceGroupName            = $ResourceGroupName`,
        `    VaultName                    = '${name}'`,
        `    Location                     = $Location`,
        `    Sku                          = '${String(node.properties.sku)}'`,
        `    EnablePurgeProtection        = $${node.properties.purgeProtection !== false}`,
        `    SoftDeleteRetentionInDays    = ${Number(node.properties.softDeleteRetentionDays)}`,
        `    EnableRbacAuthorization      = $${node.properties.rbacAuthorization !== false}`,
        `    PublicNetworkAccess          = '${node.properties.publicNetworkAccess === true ? "Enabled" : "Disabled"}'`,
        `}`,
        `New-AzKeyVault @kvParams | Out-Null`,
      ];
    case "applicationInsights": {
      const wsName = ctx.name(targetOfType(ctx, node.id, "depends_on", "logAnalytics")!.id);
      return [
        `# Application Insights ${name}`,
        `$aiParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `    Kind              = 'web'`,
        `    WorkspaceResourceId = (Get-AzOperationalInsightsWorkspace -ResourceGroupName $ResourceGroupName -Name '${wsName}').ResourceId`,
        `}`,
        `New-AzApplicationInsights @aiParams | Out-Null`,
      ];
    }
    case "logAnalytics":
      return [
        `# Log Analytics Workspace ${name}`,
        `$logParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `    Sku               = '${String(node.properties.sku)}'`,
        `    RetentionInDays   = ${Number(node.properties.retentionDays)}`,
        `}`,
        `New-AzOperationalInsightsWorkspace @logParams -Force | Out-Null`,
      ];
    case "monitorAlert":
      return [
        `# Monitor Alert ${name}`,
        `Write-Information 'Skipping alert ${name}; deploy generated Bicep/ARM for alert criteria support.' -InformationAction Continue`,
      ];
    case "actionGroup":
      return [
        `# Action Group ${name}`,
        `$ag = New-AzActionGroupReceiver -Name 'ops' -EmailReceiver -EmailAddress ${quote.powershell(String(node.properties.email))}`,
        `Set-AzActionGroup -ResourceGroupName $ResourceGroupName -Name '${name}' -ShortName '${String(node.properties.shortName)}' -Receiver $ag | Out-Null`,
      ];
    case "frontDoor":
      return [
        `# Front Door ${name}`,
        `$fdParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    SkuName           = '${String(node.properties.sku)}'`,
        `}`,
        `New-AzFrontDoorCdnProfile @fdParams | Out-Null`,
      ];
    case "applicationGateway":
      return [
        `# Application Gateway ${name}`,
        `Write-Information 'Application Gateway ${name} requires manual frontend/listener config; see Bunya docs.' -InformationAction Continue`,
      ];
    case "apiManagement":
      return [
        `# API Management ${name}`,
        `$apimParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `    Sku               = '${String(node.properties.sku)}'`,
        `    Organization      = '${String(node.properties.publisherName)}'`,
        `    AdminEmail        = ${quote.powershell(String(node.properties.publisherEmail))}`,
        `}`,
        `New-AzApiManagement @apimParams | Out-Null`,
      ];
    case "containerRegistry":
      return [
        `# Container Registry ${name}`,
        `$acrParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `    Sku               = '${String(node.properties.sku)}'`,
        `    EnableAdminUser   = $${node.properties.adminUserEnabled === true}`,
        `}`,
        `New-AzContainerRegistry @acrParams | Out-Null`,
      ];
    case "userAssignedIdentity":
      return [
        `# User-assigned Managed Identity ${name}`,
        `$umiParams = @{`,
        `    ResourceGroupName = $ResourceGroupName`,
        `    Name              = '${name}'`,
        `    Location          = $Location`,
        `}`,
        `New-AzUserAssignedIdentity @umiParams | Out-Null`,
      ];
    case "roleAssignment":
      return [
        `# Role Assignment ${name}`,
        `Write-Information 'Skipping role assignment ${name}; deploy generated Bicep/ARM for RBAC binding support.' -InformationAction Continue`,
      ];
  }
}

export function generatePowerShell(document: GraphDocument): GeneratorResult {
  const prepared = prepareGeneration(document);
  if (!prepared.ok) return prepared;
  const { ctx } = prepared;
  document = ctx.source;
  const template = templateDeployment(ctx, "powershell", NO_PRIVATE_CREATE);
  if (template) return template;
  const rg = ctx.name(ctx.rgNode.id);
  const { hasSql } = ctx;
  const paramLines = [
    `    [string]$ResourceGroupName = '${rg}',`,
    `    [string]$Location = '${document.metadata.region}'`,
  ];
  if (hasSql) {
    paramLines[paramLines.length - 1] = paramLines[paramLines.length - 1] + ",";
    paramLines.push(`    [Parameter(Mandatory)] [SecureString]$SqlAdminPassword`);
  }
  const lines: string[] = [
    ...header(document, hasSql),
    ``,
    `[CmdletBinding(SupportsShouldProcess, ConfirmImpact = 'Medium')]`,
    `param(`,
    ...paramLines,
    `)`,
    ``,
    `Set-StrictMode -Version Latest`,
    `$ErrorActionPreference = 'Stop'`,
    `$InformationPreference = 'Continue'`,
    ``,
    `Write-Information "Bunya deployment for ${document.metadata.name} (${document.metadata.environment})"`,
    `if (-not (Get-AzContext -ErrorAction SilentlyContinue)) {`,
    `    throw 'Run Connect-AzAccount before invoking this script.'`,
    `}`,
    ``,
  ];

  for (const node of ctx.order) lines.push(...emitNode(node, ctx), "");

  return {
    ok: true,
    files: [
      {
        path: "Deploy-Infrastructure.ps1",
        language: "powershell",
        content: lines.join("\n"),
      },
    ],
  };
}
